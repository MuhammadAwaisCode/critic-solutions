const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState('en');

  useEffect(() => {
    const saved = localStorage.getItem('Critic Solutions-lang') || 'en';
    applyLang(saved);
    setLang(saved);
  }, []);

  const applyLang = (code) => {
    const langObj = LANGUAGES.find(l => l.code === code) || LANGUAGES[0];
    document.documentElement.setAttribute('lang', code);
    document.documentElement.setAttribute('dir', langObj.dir);
  };

  const changeLang = (code) => {
    localStorage.setItem('Critic Solutions-lang', code);
    applyLang(code);
    setLang(code);
  };

  const t = translations[lang] || translations['en'];

  const currentLang = lang;

  return (
    <LangContext.Provider value={{ lang, currentLang, changeLang, t, translations }}>
      {children}
    </LangContext.Provider>
  );
}

export const useLang = () => useContext(LangContext);
export const useLanguage = () => useContext(LangContext);